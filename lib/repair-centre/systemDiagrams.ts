/**
 * Labelled component schematics for each Repair Centre hub.
 *
 * WHY THIS EXISTS: the owner's standing requirement is that every guide carries
 * illustrations naming the actual parts, not decorative graphics. A technician
 * reading about a fault needs to see where the named component sits in the
 * system, and what it connects to on either side.
 *
 * WHAT THESE ARE AND ARE NOT: these are FUNCTIONAL block schematics drawn from
 * engineering principle — the components a system of this type contains and how
 * they connect. They are deliberately NOT physical layout drawings of any
 * particular manufacturer's machine, because physical arrangement varies by make
 * and model and drawing one from imagination would be inventing information.
 * Every guide states that model-specific detail must be confirmed against the
 * manufacturer's documentation, and these schematics carry the same caveat.
 *
 * Nodes are placed on a simple column/row grid. Edges name what flows between
 * components, which is the part that teaches: a technician who understands that
 * the AVR senses at the main stator and feeds the exciter field can reason about
 * an excitation fault without memorising anything.
 */

export type FlowKind = 'power' | 'fuel' | 'air' | 'exhaust' | 'signal' | 'water' | 'mech' | 'dc';

export interface SystemNode {
  id: string;
  /** Component name as a technician would call it. */
  label: string;
  /** Optional qualifier shown smaller beneath the name. */
  sub?: string;
  col: number;
  row: number;
}

export interface SystemEdge {
  from: string;
  to: string;
  kind: FlowKind;
}

export interface SystemDiagram {
  title: string;
  /** Columns in the grid, used to size the viewBox. */
  cols: number;
  rows: number;
  nodes: SystemNode[];
  edges: SystemEdge[];
  /** Which flow kinds actually appear, for the legend. */
  legend: FlowKind[];
}

