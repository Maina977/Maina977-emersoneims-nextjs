#!/usr/bin/env node
/**
 * Generates lib/db/migrations/preview-setup.sql: every accounts migration, in
 * order, plus the same migration records (name + SHA-256) that migrate.cjs
 * writes, so an owner can set up a database by pasting ONE file into the
 * provider's SQL editor, and the scripts still see it as up to date.
 * A test fails if the committed file differs from what this script produces.
 *
 *   node scripts/db/build-preview-setup-sql.cjs          (writes the file)
 *   node scripts/db/build-preview-setup-sql.cjs --check  (exit 1 if out of date)
 */
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const lib = require('./accounts-lib.cjs');

function build() {
  const parts = [
    '-- GENERATED by scripts/db/build-preview-setup-sql.cjs. Do not edit by hand.',
    '-- Accounts preview database setup for the provider\'s SQL editor (Report B).',
    '-- Paste this WHOLE file into the SQL editor of a NEW, EMPTY database and run it once.',
    '-- Then run check-schema.sql: every row must say OK and the last row SCHEMA OK.',
    '-- Additive only; safe to run again. Records the same migration fingerprints as migrate.cjs.',
    '',
    'CREATE TABLE IF NOT EXISTS acct_schema_migrations (name TEXT PRIMARY KEY, sha256 TEXT NOT NULL, applied_at TIMESTAMPTZ NOT NULL DEFAULT NOW());',
    '',
  ];
  for (const f of lib.migrationFiles()) {
    const sql = fs.readFileSync(path.join(lib.MIGRATIONS_DIR, f), 'utf8').replace(/\r\n/g, '\n');
    parts.push(`-- ===== ${f} =====`, sql.trimEnd(), '', `INSERT INTO acct_schema_migrations (name, sha256) VALUES ('${f}', '${lib.sha256(sql)}') ON CONFLICT (name) DO NOTHING;`, '');
  }
  return parts.join('\n');
}

module.exports = { build };

// Only when run directly: a test that require()s this file must never rewrite the committed SQL
// (that would hide the very mismatch the test checks for).
if (require.main === module) {
  const target = path.join(lib.MIGRATIONS_DIR, 'preview-setup.sql');
  if (process.argv.includes('--check')) {
    const now = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
    if (now !== build()) { console.error('preview-setup.sql is out of date: run node scripts/db/build-preview-setup-sql.cjs'); process.exit(1); }
    console.log('preview-setup.sql is up to date');
  } else {
    fs.writeFileSync(target, build());
    console.log(`wrote ${path.relative(process.cwd(), target)}`);
  }
}
